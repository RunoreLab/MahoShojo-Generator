/**
 * ZIP 条目的固定时间戳。
 *
 * ## 为什么这个常量住在共享契约层
 *
 * 仓库里有两处独立调用 `zipSync`：Web 包打包（`@mahoshojo/web-package`）与本地库 portable
 * archive 打包（`@mahoshojo/local-library`）。两处都必须用**同一个**纪元，否则同一份内容在
 * 不同 runtime 打包出的字节不同——而这些字节的摘要是领域身份的一部分（`DESK-063`、
 * `DESK-059b`）。让它们各自写一份字面量，正是"两处各自正确、合起来错"这类缺陷的成因。
 *
 * 它不是"打包器实现细节"：纪元不同 ⇒ 归档字节不同 ⇒ 摘要不同 ⇒ 跨设备迁移后身份漂移。
 *
 * ## 为什么是本地时间构造而不是 UTC 字面量
 *
 * ZIP 的 DOS 日期字段是**无时区**的本地时间。`fflate` 的 `wzh()` 直接调用
 * `getFullYear()` / `getMonth()` / `getDate()` / `getHours()` / `getMinutes()` /
 * `getSeconds()`——全部是**本地时间 getter**——并据此编码，同时校验年份必须落在 1980–2099。
 *
 * 因此传 `new Date('1980-01-01T00:00:00.000Z')` 是错的：
 *
 * ```text
 * TZ=UTC                   → 本地 1980-01-01 00:00  → 编码 1980-01-01 → 通过
 * TZ=Asia/Shanghai (+08)   → 本地 1980-01-01 08:00  → 编码 1980-01-01 → 通过（但字节已不同）
 * TZ=America/Los_Angeles   → 本地 1979-12-31 16:00  → 年份 1979 → 抛 "date not in range 1980-2099"
 * ```
 *
 * 也就是说，同一份常量在东半球"碰巧能用"，在美洲**直接抛错**，而在所有非 UTC 时区产出的
 * 字节都不同——确定性承诺只在 UTC 机器上成立。
 *
 * 修法是构造**本地时间**的 1980-01-01 00:00:00：本地 getter 在任何时区都读回
 * 1980 / 0 / 1 / 0 / 0 / 0，于是写出的 DOS 字段恒定，而 `Date` 的绝对时刻随时区变化——
 * 但那部分**不进入字节**（fflate 不写扩展时间戳字段），因此归档逐字节可复现。
 *
 * 跨时区回归门禁见 `tests/zip-epoch-timezone.test.ts`；它会真的起子进程换 `TZ` 跑，
 * 而不是只断言常量的形状——后者在 UTC 机器上恒真，抓不到这个 bug。
 */

/**
 * 打包确定性所需的固定条目时间。
 *
 * **必须**由本地时间分量构造（`new Date(1980, 0, 1, 0, 0, 0)`）。改回
 * `new Date('1980-01-01T00:00:00.000Z')` 会让美洲用户打包失败，并让非 UTC 时区的归档字节漂移。
 */
export const ZIP_DOS_EPOCH: Date = new Date(1980, 0, 1, 0, 0, 0);