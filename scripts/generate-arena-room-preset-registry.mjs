import { createHash } from 'node:crypto';
import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(
  root,
  'apps/api/src/arena-room/generated/arena-room-preset-registry.ts',
);
const webCatalogOutputPath = path.join(
  root,
  'apps/web/lib/arena-room/generated/arena-room-preset-catalog.ts',
);
const sources = [
  { directory: 'apps/web/public/presets', kind: 'character' },
  { directory: 'apps/web/public/scenario-presets', kind: 'scenario' },
];
// `prototype` is a legitimate field in the accepted S11 scenario asset. The
// parsed server-known registry never merges payload objects, so only keys that
// can mutate ordinary object construction are rejected here.
const unsafeKeys = new Set(['__proto__', 'constructor']);

const canonicalize = (value) => {
  if (value === null || typeof value === 'string' || typeof value === 'boolean') return value;
  if (typeof value === 'number') {
    if (!Number.isFinite(value)) throw new Error('preset contains a non-finite number');
    return value;
  }
  if (Array.isArray(value)) return value.map(canonicalize);
  if (typeof value !== 'object') throw new Error('preset is not JSON');
  const output = {};
  for (const key of Object.keys(value).sort()) {
    if (unsafeKeys.has(key)) throw new Error(`preset contains unsafe key: ${key}`);
    output[key] = canonicalize(value[key]);
  }
  return output;
};

const displayName = (payload, id) => {
  for (const key of ['codename', 'name', 'title']) {
    if (typeof payload[key] === 'string' && payload[key].trim()) return payload[key].trim();
  }
  return id.replace(/\.json$/u, '');
};

const sourceType = (payload, fallback) => {
  for (const key of ['_cardType', 'type', 'templateId', 'template_id', 'template']) {
    if (typeof payload[key] === 'string' && payload[key].trim()) return payload[key].trim();
  }
  return fallback;
};

const loadEntries = async () => {
  const entries = [];
  for (const source of sources) {
    const directory = path.join(root, source.directory);
    const names = (await fs.readdir(directory))
      .filter((name) => name.endsWith('.json'))
      .sort((left, right) => left.localeCompare(right, 'en'));
    for (const id of names) {
      const sourcePath = path.join(directory, id);
      const payload = canonicalize(JSON.parse(await fs.readFile(sourcePath, 'utf8')));
      const canonicalJson = JSON.stringify(payload);
      entries.push({
        id,
        kind: source.kind,
        versionToken: `sha256:${createHash('sha256').update(canonicalJson).digest('hex')}`,
        displayName: displayName(payload, id),
        sourceType: sourceType(payload, source.kind),
        payload,
        sourcePath: path.relative(root, sourcePath),
      });
    }
  }
  const identities = new Set();
  for (const entry of entries) {
    const identity = `${entry.kind}\u0000${entry.id}`;
    if (identities.has(identity)) {
      throw new Error(`duplicate preset identity: ${entry.kind}:${entry.id}`);
    }
    identities.add(identity);
  }
  return entries;
};

const render = (entries) => `${[
  '/**',
  ' * Generated by scripts/generate-arena-room-preset-registry.mjs.',
  ' * Do not edit by hand. Runtime must not import apps/web assets directly.',
  ' */',
  "import type { JsonValue } from '@mahoshojo/contracts/json-value';",
  '',
  'export type GeneratedArenaRoomPresetEntry = Readonly<{',
  '  id: string;',
  "  kind: 'character' | 'scenario';",
  '  versionToken: string;',
  '  displayName: string;',
  '  sourceType: string;',
  '  payload: JsonValue;',
  '  sourcePath: string;',
  '}>;',
  '',
  'export const GENERATED_ARENA_ROOM_PRESETS = ',
].join('\n')}${JSON.stringify(entries, null, 2)} as const satisfies readonly GeneratedArenaRoomPresetEntry[];\n`;

const renderWebCatalog = (entries) => `${[
  '/**',
  ' * Generated by scripts/generate-arena-room-preset-registry.mjs.',
  ' * Web-safe metadata only; payloads remain server-known.',
  ' */',
  'export type ArenaRoomPresetCatalogEntry = Readonly<{',
  '  id: string;',
  "  kind: 'character' | 'scenario';",
  '  versionToken: string;',
  '  displayName: string;',
  '  sourceType: string;',
  '}>;',
  '',
  'export const ARENA_ROOM_PRESET_CATALOG = ',
].join('\n')}${JSON.stringify(entries.map((entry) => ({
  id: entry.id,
  kind: entry.kind,
  versionToken: entry.versionToken,
  displayName: entry.displayName,
  sourceType: entry.sourceType,
})), null, 2)} as const satisfies readonly ArenaRoomPresetCatalogEntry[];\n`;

const entries = await loadEntries();
const generated = render(entries);
const webCatalog = renderWebCatalog(entries);
if (process.argv.includes('--check')) {
  const current = await fs.readFile(outputPath, 'utf8').catch(() => '');
  const currentWebCatalog = await fs.readFile(webCatalogOutputPath, 'utf8').catch(() => '');
  if (current !== generated || currentWebCatalog !== webCatalog) {
    console.error('Arena Room preset registry/catalog is stale; run pnpm generate:arena-room-presets.');
    process.exitCode = 1;
  }
} else {
  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, generated);
  await fs.mkdir(path.dirname(webCatalogOutputPath), { recursive: true });
  await fs.writeFile(webCatalogOutputPath, webCatalog);
  console.info(`Generated ${path.relative(root, outputPath)} and ${path.relative(root, webCatalogOutputPath)}`);
}
