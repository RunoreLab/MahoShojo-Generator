import { readFile, readdir, lstat, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packageRoot = path.join(root, 'packages/web-package');
const mediaTypes = { '.html': 'text/html', '.css': 'text/css', '.js': 'text/javascript', '.json': 'application/json', '.md': 'text/markdown', '.txt': 'text/plain', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg', '.webp': 'image/webp', '.gif': 'image/gif', '.woff2': 'font/woff2', '.mp3': 'audio/mpeg', '.mp4': 'video/mp4' };
let verifier;
async function getVerifier() {
  if (!verifier) {
    const result = await build({
      stdin: { contents: "export { verifyWebPackage, digestWebPackageBytes } from './packages/web-package/src/verify.ts'; export { WebPackagePathSchema } from './packages/contracts/src/web-package.ts';", resolveDir: root },
      bundle: true, platform: 'node', format: 'esm', write: false,
    });
    verifier = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
  }
  return verifier;
}

/** Filesystem is authoring authority; the wire manifest still contains verified descriptors. */
export async function compilePreset(directory) {
  const { verifyWebPackage, digestWebPackageBytes, WebPackagePathSchema } = await getVerifier();
  const files = [];
  async function walk(relative = '') {
    const current = path.join(directory, relative);
    if (!(await lstat(current)).isDirectory()) throw new Error(`Preset must be a real directory: ${current}`);
    for (const name of (await readdir(current)).sort()) {
      const logical = relative ? `${relative}/${name}` : name;
      WebPackagePathSchema.parse(logical);
      const absolute = path.join(directory, logical);
      const stat = await lstat(absolute);
      if (stat.isSymbolicLink()) throw new Error(`Symlinks are not package assets: ${logical}`);
      if (stat.isDirectory()) { await walk(logical); continue; }
      if (!stat.isFile()) throw new Error(`Unsupported asset: ${logical}`);
      if (logical === 'web-package.json') continue;
      const mediaType = mediaTypes[path.extname(logical).toLowerCase()];
      if (!mediaType) throw new Error(`Unknown asset media type: ${logical}`);
      const bytes = await readFile(absolute);
      files.push({ path: logical, mediaType, bytes });
    }
  }
  await walk();
  const source = JSON.parse(await readFile(path.join(directory, 'web-package.json'), 'utf8'));
  if ('files' in source) throw new Error('Source manifest must not enumerate generated files');
  const descriptors = await Promise.all(files.map(async ({ path, mediaType, bytes }) => ({ path, mediaType, size: bytes.length, digest: await digestWebPackageBytes(bytes) })));
  const verified = await verifyWebPackage({ ...source, files: descriptors }, files);
  return { ref: verified.ref, manifest: verified.manifest, files: files.map(({ path, bytes }) => ({ path, base64: bytes.toString('base64') })) };
}

export async function generate({ check = false } = {}) {
  const catalog = JSON.parse(await readFile(path.join(packageRoot, 'preset-catalog.json'), 'utf8'));
  const revisions = [];
  const directories = new Set();
  const identities = new Set();
  for (const entry of catalog) {
    if (!/^[a-z0-9][a-z0-9-]*$/u.test(entry.directory) || directories.has(entry.directory)) throw new Error('Invalid or duplicate preset directory');
    if (!['active', 'retained'].includes(entry.status)) throw new Error('Invalid preset status');
    directories.add(entry.directory);
    const revision = await compilePreset(path.join(packageRoot, 'presets', entry.directory));
    if (JSON.stringify(revision.ref) !== JSON.stringify(entry.packageRef)) throw new Error(`Pinned revision changed: ${entry.directory}. Publish a new version and pin its digest.`);
    const identity = `${revision.ref.id}@${revision.ref.version}`;
    if (identities.has(identity)) throw new Error(`Duplicate preset revision: ${identity}`);
    identities.add(identity);
    revisions.push(revision);
  }
  const banner = '// Generated by scripts/generate-web-package-presets.mjs. Edit static preset directories, not this file.\n';
  const outputs = {
    'preset-metadata.ts': `${banner}import type { WebPackageRef } from '@mahoshojo/contracts/web-package';\nexport const PRESET_METADATA: readonly Readonly<{ packageRef: WebPackageRef; title: string; description: string; downloadUrl: string; status: 'active' | 'retained' }>[] = ${JSON.stringify(catalog.map(({ directory: _directory, ...entry }) => entry), null, 2)};\n`,
    'preset-files.ts': `${banner}import type { WebPackageManifest, WebPackageRef } from '@mahoshojo/contracts/web-package';\nexport const PRESET_REVISIONS: readonly { ref: WebPackageRef; manifest: WebPackageManifest; files: readonly { path: string; base64: string }[] }[] = ${JSON.stringify(revisions, null, 2)};\n`,
  };
  const outputDir = path.join(packageRoot, 'src/generated');
  if (!check) await mkdir(outputDir, { recursive: true });
  for (const [name, content] of Object.entries(outputs)) {
    const target = path.join(outputDir, name);
    if (check) {
      const existing = await readFile(target, 'utf8').catch(() => null);
      if (existing !== content) throw new Error(`Stale generated preset: ${name}; run pnpm generate:web-package-presets`);
    } else await writeFile(target, content);
  }
  console.log(`Web Package presets ${check ? 'checked' : 'generated'}: ${revisions.length}`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await generate({ check: process.argv.includes('--check') });
}
